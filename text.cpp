void setPixel(SDL_Surface* s, int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || x >= s->w || y >= s->h) return;
    uint32_t* px = (uint32_t*)s->pixels + (size_t)y * s->pitch / 4 + x;
    *px = color;
}

void drawText(SDL_Surface* s, int x, int y, const char* text, uint32_t color, int scale) {
    const auto& f = font();
    int pen = x;
    for (const char* p = text; *p; p++) {
        auto it = f.find(*p);
        if (it == f.end()) { pen += 6 * scale; continue; }
        const Glyph& g = it->second;
        for (int r = 0; r < 7; r++) {
            uint8_t mask = g.rows[r];
            for (int c = 0; c < 5; c++) {
                if (mask & (1 << (4 - c))) {
                    for (int yy = 0; yy < scale; yy++)
                        for (int xx = 0; xx < scale; xx++)
                            setPixel(s, pen + c * scale + xx, y + r * scale + yy, color);
                }
            }
        }
        pen += 6 * scale;
    }
}